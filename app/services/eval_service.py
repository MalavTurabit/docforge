"""
app/services/eval_service.py
RAGAS 0.4.3 evaluation using HuggingFace datasets library.

Flow:
  1. Build a datasets.Dataset with required columns
  2. Generate synthetic reference using LLM (enables all 4 metrics)
  3. Run ragas.evaluate() with all 4 metrics
  4. Return scores dict

Columns in dataset:
  - question          : the user query
  - answer            : the generated answer
  - contexts          : list of retrieved chunk texts
  - ground_truth      : synthetic reference generated by LLM
"""

import os
import logging
from typing import Optional

logger = logging.getLogger("docforge.eval")


def _get_llm():
    from langchain_openai import AzureChatOpenAI
    return AzureChatOpenAI(
        azure_endpoint   = os.getenv("AZURE_LLM_ENDPOINT"),
        api_key          = os.getenv("AZURE_OPENAI_LLM_KEY"),
        azure_deployment = os.getenv("AZURE_LLM_DEPLOYMENT_41_MINI"),
        api_version      = os.getenv("AZURE_LLM_API_VERSION", "2024-02-01"),
        temperature      = 0,
    )


def _get_embeddings():
    from langchain_openai import AzureOpenAIEmbeddings
    return AzureOpenAIEmbeddings(
        azure_endpoint      = os.getenv("AZURE_OPENAI_EMB_ENDPOINT"),
        api_key             = os.getenv("AZURE_OPENAI_EMB_KEY"),
        azure_deployment    = os.getenv("AZURE_OPENAI_EMB_DEPLOYMENT"),
        openai_api_version  = os.getenv("AZURE_OPENAI_EMB_API_VERSION", "2024-02-01"),
    )


def _generate_reference(query: str, contexts: list[str], llm) -> str:
    """
    Generate a synthetic ground truth answer from the retrieved context.
    This enables ContextPrecision and ContextRecall metrics which
    require a reference answer to compare against.
    """
    context_text = "\n\n".join(contexts[:3])  # use top 3 contexts
    prompt = (
        f"Based ONLY on the following context, write the ideal factual answer "
        f"to the question. Be concise and accurate.\n\n"
        f"Context:\n{context_text}\n\n"
        f"Question: {query}\n\n"
        f"Ideal answer:"
    )
    try:
        response = llm.invoke(prompt)
        return response.content.strip()
    except Exception as e:
        logger.warning(f"[eval] Reference generation failed: {e}")
        return ""


def evaluate_rag(
    query:   str,
    answer:  str,
    chunks:  list[dict],
) -> dict:
    """
    Run RAGAS evaluation using datasets.Dataset.

    All 4 metrics:
      - Faithfulness      (reference-free)
      - AnswerRelevancy   (reference-free)
      - ContextPrecision  (uses synthetic reference)
      - ContextRecall     (uses synthetic reference)
    """
    try:
        from datasets import Dataset
        from ragas import evaluate
        from ragas.metrics import (
            Faithfulness,
            AnswerRelevancy,
            ContextPrecision,
            ContextRecall,
        )

        # Build context list from chunks
        contexts = [
            c.get("raw_text", "").strip()
            for c in chunks
            if c.get("raw_text", "").strip()
        ]

        if not contexts:
            logger.warning("[eval] No contexts for RAGAS")
            return _empty_scores()

        llm = _get_llm()

        # Generate synthetic reference to enable all 4 metrics
        logger.info("[eval] Generating synthetic reference…")
        reference = _generate_reference(query, contexts, llm)

        if not reference:
            # Fallback — run only reference-free metrics
            logger.warning("[eval] No reference — running reference-free only")
            return _run_reference_free(query, answer, contexts, llm)

        # Build dataset using datasets library
        # ragas expects these exact column names
        data = {
            "question":    [query],
            "answer":      [answer],
            "contexts":    [contexts],
            "ground_truth": [reference],
        }
        dataset = Dataset.from_dict(data)

        logger.info(f"[eval] Running RAGAS (all 4 metrics) — query='{query[:60]}'")

        result = evaluate(
            dataset          = dataset,
            metrics          = [
                Faithfulness(),
                AnswerRelevancy(),
                ContextPrecision(),
                ContextRecall(),
            ],
            llm              = llm,
            embeddings       = _get_embeddings(),
            show_progress    = False,
            raise_exceptions = False,
        )

        df = result.to_pandas()
        scores = {
            "faithfulness":      _safe(df, "faithfulness"),
            "answer_relevancy":  _safe(df, "answer_relevancy"),
            "context_precision": _safe(df, "context_precision"),
            "context_recall":    _safe(df, "context_recall"),
        }
        logger.info(f"[eval] RAGAS scores: {scores}")
        return scores

    except Exception as e:
        logger.error(f"[eval] RAGAS failed: {e}")
        return _empty_scores()


def _run_reference_free(
    query: str,
    answer: str,
    contexts: list[str],
    llm,
) -> dict:
    """Fallback — run only reference-free metrics."""
    try:
        from datasets import Dataset
        from ragas import evaluate
        from ragas.metrics import Faithfulness, AnswerRelevancy

        data = {
            "question": [query],
            "answer":   [answer],
            "contexts": [contexts],
        }
        dataset = Dataset.from_dict(data)

        result = evaluate(
            dataset          = dataset,
            metrics          = [Faithfulness(), AnswerRelevancy()],
            llm              = llm,
            embeddings       = _get_embeddings(),
            show_progress    = False,
            raise_exceptions = False,
        )

        df = result.to_pandas()
        return {
            "faithfulness":      _safe(df, "faithfulness"),
            "answer_relevancy":  _safe(df, "answer_relevancy"),
            "context_precision": None,
            "context_recall":    None,
        }
    except Exception as e:
        logger.error(f"[eval] Reference-free fallback failed: {e}")
        return _empty_scores()


def _safe(df, col: str) -> Optional[float]:
    try:
        if col not in df.columns:
            return None
        val = df[col].iloc[0]
        return round(float(val), 3) if val is not None else None
    except Exception:
        return None


def _empty_scores() -> dict:
    return {
        "faithfulness":      None,
        "answer_relevancy":  None,
        "context_precision": None,
        "context_recall":    None,
    }


def score_label(score: Optional[float]) -> str:
    if score is None: return "⚪"
    if score >= 0.8:  return "🟢"
    if score >= 0.6:  return "🟡"
    return "🔴"